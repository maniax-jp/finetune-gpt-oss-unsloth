def create_reasoning_dataset():
    """
    推論データをHarmony形式で作成
    """
    print("=" * 80)
    print("推論データセット作成")
    print("=" * 80)
    print(f"\n目標: {len(REASONING_SAMPLES)}サンプルの推論データを作成")
    print("形式: Harmony形式 + Analysis channel")
    print()

    reasoning_data = []

    for i, sample in enumerate(REASONING_SAMPLES, 1):
        # Harmony形式に変換（Analysis channel付き）
        harmony_item = {
            "messages": [
                {
                    "role": "user",
                    "content": sample["question"]
                },
                {
                    "role": "assistant",
                    "content": (
                        f"<|channel|>analysis<|message|>{sample.get('analysis', '分析中...')}<|end|>"
                        f"<|channel|>final<|message|>{sample.get('final_answer', '回答中...')}"
                    )
                }
            ]
        }
        reasoning_data.append(harmony_item)

        if i % 10 == 0:
            print(f"  処理済み: {i}/{len(REASONING_SAMPLES)}")

    # JSONLファイルとして保存
    output_path = "dataset/takaichi_sanae_reasoning_pilot.jsonl"
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        for item in reasoning_data:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')

    print(f"\n✅ 推論データセット作成完了")
    print(f"   保存先: {output_path}")
    print(f"   サンプル数: {len(reasoning_data)}")
    print(f"\n【データセット構成】")
    print(f"   推論データ: {len(reasoning_data)}サンプル（新規作成）")
    print(f"   非推論データ: 455サンプル（既存のmerged_collection.json）")
    print(f"\n【次のステップ】")
    print(f"   1. 推論データを既存データとマージ")
    print(f"   2. 推論データ比率を段階的に増加")
    print(f"   3. 目標: 75%推論 + 25%非推論")

    return output_path


if __name__ == "__main__":
    create_reasoning_dataset()
